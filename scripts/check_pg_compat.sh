#!/bin/bash
#
# check_pg_compat.sh — PG15/16/17/18 syntax-only compatibility gate for
# the duckdb_fdw C sources.
#
# Usage:
#   scripts/check_pg_compat.sh            # check all of 15 16 17 18
#   scripts/check_pg_compat.sh 15 18      # check only the listed versions
#
# What it does, per requested PG major version V:
#   1. Resolves a header tree for V:
#        a. /tmp/pg${V}_include              (hand-prepared tree, if present)
#        b. a locally installed server tree (pg_config / pg_config-${V}
#           whose major version matches V — a complete, authoritative set)
#        c. auto-setup: downloads the official source tarball from
#           ftp.postgresql.org and assembles a syntax-check tree (src/include
#           plus stubs for the build-generated headers: pg_config.h,
#           pg_config_os.h, pg_config_ext.h, utils/errcodes.h,
#           utils/fmgroids.h, utils/fmgrprotos.h, nodes/nodetags.h,
#           storage/lwlocknames.h, catalog/pg_*_d.h, catalog/syscache_ids.h).
#           _d.h / fmgroids stubs are borrowed from any locally installed PG
#           tree when available (see FDW_PG_STUB_SRC below).
#   2. Runs:  gcc -fsyntax-only -I <include tree> -I <repo root> <file>.c
#      for every C file in the Makefile OBJS list.
#
# Environment overrides:
#   FDW_PG_CACHE      cache dir for downloaded tarballs (default /tmp/fdw_pg_compat)
#   FDW_PG15_TARBALL  e.g. 15.10 (default: per-version table below)
#   FDW_PG16_TARBALL  e.g. 16.6
#   FDW_PG18_TARBALL  e.g. 18.0
#   FDW_PG_STUB_SRC   installed PG server include dir used to borrow the
#                     generated _d.h / fmgroids.h stubs
#                     (default: pg_config --includedir-server, if any)
#   FDW_CC            compiler (default: gcc)
#
# The syntax-only check cannot catch link-time or semantic issues; it is the
# cheap gate that reproduces the CI "expected 10 have 11" class of failures
# (changed planner API signatures, moved structs/headers) in seconds.

set -u

REPO_ROOT=$(cd "$(dirname "$0")/.." && pwd)
CC=${FDW_CC:-gcc}
CACHE=${FDW_PG_CACHE:-/tmp/fdw_pg_compat}
STUB_SRC=${FDW_PG_STUB_SRC:-$(pg_config --includedir-server 2>/dev/null || true)}

# C sources matching the Makefile OBJS list (OBJS = *.o of these).
SOURCES="connection.c option.c deparse.c duckdb_fdw.c import.c sql_utils.c runtime_guard.c"

# Default tarball versions (bump when you need a newer patch release; the
# signatures checked here are stable within a major version).
TARBALL_VERSION() {
    case "$1" in
        15) echo "${FDW_PG15_TARBALL:-15.10}" ;;
        16) echo "${FDW_PG16_TARBALL:-16.6}" ;;
        17) echo "${FDW_PG17_TARBALL:-17.9}" ;;
        18) echo "${FDW_PG18_TARBALL:-18.0}" ;;
        *)  return 1 ;;
    esac
}

# Minimal pg_config.h for the auto-setup path (glibc Linux only).  A
